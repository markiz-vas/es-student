//Защита от повторного включения (англ. include guard) 
#pragma once

// стандартного ввода-вывода — тот же, что в любой программе на C
#include <stdio.h>

// Печатает, что за прибор перед вами и какая в нём прошивка
void log_version(void);
// Печатает подпись перед текстом сообщения (в LOG_ERR, LOG_INF, LOG_DBG)
void log_prefix(const char *level, const char *function, int line);


// Определение уровней вывода лога
// Порог LOG_LEVEL читается как «печатать всё, что не выше этого числа».
#define LOG_LEVEL_ERR 1     // ошибка (ERR) — то, что пошло не так
#define LOG_LEVEL_INF 2     // сведение (INF) — событие, о котором стоит знать всегда
#define LOG_LEVEL_DBG 3     // отладка (DBG) — подробности, нужные только при разборе

// Если Лог-уровень раньше не определен, то тут его определение (по умолчанию)
#ifndef LOG_LEVEL
#define LOG_LEVEL LOG_LEVEL_INF
#endif

// ТЕОРИЯ //
// __DATE__ и __TIME__ — дата и время сборки, их тоже подставляет компилятор. 
// __VA_ARGS__ — это «всё, что передали». 
//      Благодаря ему макрос принимает столько же аргументов, сколько printf(): 
//      и одну строку, и строку с числами.
// __func__ и __LINE__ подставляет компилятор: имя функции, внутри которой стоит вызов, 
//      и номер строки в файле. Вы их не пишете — 
//      и именно поэтому подпись всегда верна, даже когда код переехал.
// Проверка LOG_LEVEL >= LOG_LEVEL_INF — то самое отсечение. 
//      Условие известно на этапе компиляции, поэтому при пониженном пороге компилятор 
//      выбрасывает и вызов, и саму строку сообщения: в образе их не остаётся.
// Обёртка do { … } while (0) выглядит бессмысленной — цикл, который выполняется ровно один раз. 
//      Она нужна, чтобы макрос вёл себя как одна инструкция: без неё запись вида 
//      if (условие) LOG_INF("…"); else … развалилась бы на части и перестала собираться. 
//      Это стандартный приём, и встречать его вы будете в любом чужом коде с макросами.

// Макрос ошибок (ERR)
#define LOG_ERR(...)                                \
    do {                                            \
        if (LOG_LEVEL >= LOG_LEVEL_ERR) {           \
            log_prefix("err", __func__, __LINE__);  \
            printf(__VA_ARGS__);                    \
        }                                           \
    } while (0)

// Макрос свдений (INF)
#define LOG_INF(...)                                \
    do {                                            \
        if (LOG_LEVEL >= LOG_LEVEL_INF) {           \
            log_prefix("inf", __func__, __LINE__);  \
            printf(__VA_ARGS__);                    \
        }                                           \
    } while (0)

// Макрос отладки (DBG)
#define LOG_DBG(...)                                \
    do {                                            \
        if (LOG_LEVEL >= LOG_LEVEL_DBG) {           \
            log_prefix("dbg", __func__, __LINE__);  \
            printf(__VA_ARGS__);                    \
        }                                           \
    } while (0)





