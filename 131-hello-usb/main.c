//varALL//  // стандартного ввода-вывода — тот же, что в любой программе на C
#include <stdio.h>
//varALL//  // заголовочные файлы для sleep_ms, stdio_init_all
#include "pico/stdlib.h"
//varALL//  // заголовочные файлы для gpio_init
//var0//    // заголовочные файлы для gpio_set_dir, gpio_put 
#include "hardware/gpio.h"


//varALL// // Нормер выхода
const uint LED_PIN = 16;
const uint BUTTON_PIN = 15;

// Константа 20mc для борьбы с дребезгом
const uint DEBOUNCE_MS = 20;

// Функция определяет, был ли дребезг
// Считывает два значение, возвращает true, если оба true
bool get_button_debounce(uint pin)
{
    bool state = gpio_get(pin);     // Считали первое значение
    sleep_ms(DEBOUNCE_MS);          // подождали DEBOUNCE_MS
    return state && gpio_get(pin);  // Считали второе значение
}

int main()
{
    //varALL// // подготовить стандартный ввод-вывод по каналам, включённым в CMake
    //varALL// // pico_enable_stdio_usb (${PROJECT_NAME} 1) // CMakeLists.txt
    //varALL// // pico_enable_stdio_uart(${PROJECT_NAME} 0) // CMakeLists.txt
    stdio_init_all();

    // ТЕОРИЯ //
    // Обратите внимание, что канал включается целиком, в обе стороны сразу: 
    // отдельно настраивать приём не нужно. Забыть можно любую из двух строк, 
    // и обе ошибки выглядят одинаково неприятно — проект собирается, плата работает, 
    // светодиод мигает, а терминал молчит. 
    // Никакого сообщения об ошибке при этом не будет: сборке нечего сообщать, 
    // ведь и printf() на месте, и канал формально существует, 
    // просто он не попал в образ или не был включён. 


    //varALL// // Инициализация вывода  // отдать вывод модулю GPIO
    //var0// // Вывод работает на выход // задать направление «выход»
    gpio_init(LED_PIN);                 // инициализируем пин светодиода
    gpio_set_dir(LED_PIN, GPIO_OUT);    // настраиваем пин светодиода на выход
    
    //varALL// // Инициализация вывода  // отдать вывод модулю GPIO
    //var0// // Вывод работает на вход  // задать направление «вход»
    //var0// // Подключаем к подтягивающему регистру
    gpio_init(BUTTON_PIN);              // инициализируем пин кнопки
    gpio_set_dir(BUTTON_PIN, GPIO_IN ); // настраиваем пин кнопки на вход
    gpio_pull_up(BUTTON_PIN);           // подтягиваем кнопку к питанию

    // ТЕОРИЯ //
    // Пока кнопка не нажата, BUTTON_PIN ни к чему не подключён — 
    // на нём нет ни нуля, ни единицы, и читаться будет случайный мусор. 
    // Чтобы этого не было, внутри микроконтроллера есть подтягивающий резистор: 
    // он мягко притягивает вывод к питанию, и незанятый вход читается как единица

    // led - светит ли светодиод, 
    // previous - что вывод показывал на прошлом шаге цикла
    bool led = true;
    bool previous = false;

    // Бесконечный цикл (Суперцикл) - это обязательное условие,
    // Так как все программы запускаются на Земле 1 раз
    while (1)
    {
        // Включить светодиод (по умолчанию)
        gpio_put(LED_PIN, led);
        
        // Проверяйте не состояние, а его смену. Суперцикл крутится тысячи раз в секунду. 
        // Если переключать светодиод, пока кнопка нажата, он будет мигать всё время нажатия. 
        // Переключать нужно в момент, когда вывод перешёл из единицы в ноль, то есть когда кнопку нажали:
        // bool current = gpio_get(BUTTON_PIN);

        // Замена прямого чтения вывода (gpio_|_get) вызовом функции (get_button_debounce)
        bool current = get_button_debounce(BUTTON_PIN); // читаем состояние пина кнопки с задержкой
        
        // Если кнопка нажата (false - нажата, true - отжата)
        if (previous == true && current == false)       // проверяем, нужно ли переключить светодиод
        {
            // Переключить светодиод
            led = !led; 
            gpio_put(LED_PIN, led);
        }
        // Запоминаем, что нажато было раньше (чтобы не мигала)
        previous = current;     // запоминаем текущее состояние пина кнопки, как предыдущее

        // Тест вывод сообщения через кабель usb в виртуальный COM-port
        // printf("Hello, world!  %d\n", led);
        printf("Hello, world!\n"); //1.3.2 check-1-3-2.py
        sleep_ms(1000);
    }
}