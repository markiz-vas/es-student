// stdio-text-protocol.h // заголовочный файл протокола обмена текстовыми командами
//Защита от повторного включения (англ. include guard) 
#pragma once

// ради типа bool
#include <stdbool.h>
// ради типа uintptr_t, uint32_t, uint16_t, uint8_t
#include <stdint.h>

/// TASK 2.3.1 ///

// Макросы
#define STDIO_TEXT_PROTOCOL_LINE_SIZE 64    // Длина Буфера (63 символа + '\0')
#define STDIO_TEXT_PROTOCOL_MAX_ARGS 4      // Количество аргументов (отличие от main.c, args[0] - это аргумент, а не команда)


// Структура, которая содержит информацию о принятой команде. (тип - структура)
//  команда, принятая из одной строки (если команда принята целиком и без ошибок)
//  Если произошла ошибка (или команда не целиком), то данная структура не возвращается
typedef struct
{
    const char *name;   // имя команды
    uint32_t    argc;   // Количество аргументов (1 -- имя; 2-5 -- параметры; 0 -- пустая строка; >5 -- слишком много аргументов)
    const char *argv[STDIO_TEXT_PROTOCOL_MAX_ARGS]; // Массив ссылок на аргументы (тип char*), не больше 4 (argv[0]-argv[3])

    // строка длиннее буфера или аргументов больше, чем помещается в argv:
    // команда принята не целиком, выполнять её нельзя
    bool truncated; // по умолчанию false, если true - значит переполнение
} command_t;


// Конструктор протокола (инициализация)
void stdio_text_protocol_init(void);

// Читает один символ, не ожидая его. Когда строка закончена, возвращает
// команду, иначе NULL. Команда действительна до следующего вызова.
const command_t *stdio_text_protocol_handle(void);