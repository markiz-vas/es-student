// стандартного ввода-вывода — тот же, что в любой программе на C
#include <stdio.h>
// для работы со строками, strcmp()
#include <string.h>
// заголовочный файл светодиода #include "led\led.h"
#include "led.h"
// заголовочный файл для лога ошибок #include "logging\log.h"
#include "log.h"
// заголовочный файл лога информации о приборе #include "device\device.h"
#include "device.h"

// Нормер выхода
const uint BUTTON_PIN = 15;

// Константа 20mc для борьбы с дребезгом
const uint DEBOUNCE_MS = 20;

// Буфер и его длина (32 символа) (глобальная переменная)
#define LINE_SIZE 32
char line[LINE_SIZE];
uint line_length = 0;


// Функция определяет, был ли дребезг
// Считывает два значение, возвращает true, если оба true
bool get_button_debounce(uint pin)
{
    bool state = gpio_get(pin);     // Считали первое значение
    sleep_ms(DEBOUNCE_MS);          // подождали DEBOUNCE_MS
    return state && gpio_get(pin);  // Считали второе значение
}

// Разбирает команду и возвращаем новое состояние светодиода
void handle_command(const char *command)
{
    // Расшифровка команд, command явно приводится к char
    if (strcmp(command, "enable") == 0) { 
        led_set(true);  // включить
        // Вывод сообщения через кабель usb в виртуальный COM-port
        LOG_INF("led %s\n", led_is_on() ? "on" : "off");
    } else if (strcmp(command, "disable") == 0) {
        led_set(false); // погасить
        // Вывод сообщения через кабель usb в виртуальный COM-port
        LOG_INF("led %s\n", led_is_on() ? "on" : "off");
    } else if (strcmp(command, "version") == 0) {
        // Прибор печатает строку журнала о версии прошивки
        log_version();
    } else if (strcmp(command, "info") == 0) {
        // Прибор печатает паспорт устройства (версия железа и происхождения)
        device_info();
    } else {
        // Правило хорошего тона, вернуть неизвестную команду
        LOG_ERR("unknown command: %s\n", command);
    }
}

// Функция очистки слова из COM-порта
void clear_line(void) 
{
    for (int i = 0; i < LINE_SIZE; i++) line[i] = '\0';
    line_length = 0;
}

// Функция считывания слова из COM-порта
void read_line(void)
{
    // Считали один символ из строки
    int symbol = getchar_timeout_us(0);
    if (symbol == PICO_ERROR_TIMEOUT) {
        return; // Если пусто - ранний выход
    }

    // Проверка на конец строки
    if (symbol == '\r' || symbol == '\n')    {
        putchar('\n'); // Печать в консоль
        line[line_length] = '\0';   // символ конца строки (обязательный)
        if (line_length > 0) {
            LOG_DBG("got %s\n", line);  // Печать строки целиком
            handle_command(line);       // расшифровка команды
        }
        line_length = 0;
        return;
    }

    // Проверяем, что есть место под конечный символ ('\0')
    if (line_length + 1 < LINE_SIZE)    {
        line[line_length] = (char)symbol;   // собираем строку из char
        line_length = line_length + 1;      // увеличиваем длину строки
        putchar(symbol); // Печать в консоль
        // ТЕОРИЯ //
        // Возврат символа в терминал. putchar(symbol) печатает то, что вы набрали. 
        // Прошивка обязана это делать сама: терминал показывает не ваши нажатия, 
        // а то, что ответил прибор. Без этой строки набор идёт вслепую.
    }
}






int main()
{
    // подготовить стандартный ввод-вывод по каналам, включённым в CMake
    // pico_enable_stdio_usb (${PROJECT_NAME} 1) // CMakeLists.txt
    // pico_enable_stdio_uart(${PROJECT_NAME} 0) // CMakeLists.txt
    stdio_init_all();

    // ТЕОРИЯ //
    // Обратите внимание, что канал включается целиком, в обе стороны сразу: 
    // отдельно настраивать приём не нужно. Забыть можно любую из двух строк, 
    // и обе ошибки выглядят одинаково неприятно — проект собирается, плата работает, 
    // светодиод мигает, а терминал молчит. 
    // Никакого сообщения об ошибке при этом не будет: сборке нечего сообщать, 
    // ведь и print_f() на месте, и канал формально существует, 
    // просто он не попал в образ или не был включён. 

    // Инициализация, настраивает вывод на выход и гасит/зажигает светодиод
    led_init();

    // Инициализация вывода     // отдать вывод модулю GPIO
    // Вывод работает на вход   // задать направление «вход»
    // Подключаем к подтягивающему регистру
    gpio_init(BUTTON_PIN);              // инициализируем пин кнопки
    gpio_set_dir(BUTTON_PIN, GPIO_IN ); // настраиваем пин кнопки на вход
    gpio_pull_up(BUTTON_PIN);           // подтягиваем кнопку к питанию

    // ТЕОРИЯ //
    // Пока кнопка не нажата, BUTTON_PIN ни к чему не подключён — 
    // на нём нет ни нуля, ни единицы, и читаться будет случайный мусор. 
    // Чтобы этого не было, внутри микроконтроллера есть подтягивающий резистор: 
    // он мягко притягивает вывод к питанию, и незанятый вход читается как единица

    // previous - что вывод показывал на прошлом шаге цикла (нужно для кнопки)
    bool previous = false;

    // Бесконечный цикл (Суперцикл) - это обязательное условие,
    // Так как все программы запускаются на Земле 1 раз
    while (1)
    {
        // Проверяйте не состояние, а его смену. Суперцикл крутится тысячи раз в секунду. 
        // Если переключать светодиод, пока кнопка нажата, он будет мигать всё время нажатия. 
        // Переключать нужно в момент, когда вывод перешёл из единицы в ноль, то есть когда кнопку нажали:
        // bool current = gpio_get(BUTTON_PIN);

        // Замена прямого чтения вывода (gpio_get) вызовом функции (get_button_debounce)
        bool current = get_button_debounce(BUTTON_PIN); // читаем состояние пина кнопки с задержкой
        // Если кнопка нажата (false - нажата, true - отжата)
        if (previous == true && current == false)       // проверяем, нужно ли переключить светодиод
        {
            // Переключить светодиод
            led_toggle();
            // Вывод сообщения через кабель usb в виртуальный COM-port
            LOG_INF("led %s\n", led_is_on() ? "on" : "off");
        }
        // Запоминаем, что нажато было раньше (чтобы не мигала)
        previous = current;     // запоминаем текущее состояние пина кнопки, как предыдущее

        // ТЕОРИЯ //
        // Нулевое время ожидания превращает вызов в вопрос «есть ли что-нибудь для меня?»: 
        // если символ в буфере есть, функция вернёт его код (int c), 
        // если нет — вернёт PICO_ERROR_TIMEOUT и тут же передаст управление дальше
        // int c = getchar_timeout_us(0); // 0 мкс ожидания: забрать символ, только если он уже принят
        // if (c != PICO_ERROR_TIMEOUT) { print_f("got %c\n", (char)c); } // PICO_ERROR_TIMEOUT означает «символов не было»

        // Считываем строку на вход
        read_line();

    }// Суперцикл
}